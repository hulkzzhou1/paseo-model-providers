export function translate(message: string, language: Language): string {
  if (language === "zh-CN") return message;
  if (english[message]) return english[message];
  const catalog = /^无法获取模型（HTTP (\d+)），可手动填写模型 ID。$/.exec(message);
  if (catalog) return `Could not fetch models (HTTP ${catalog[1]}). Enter model IDs manually.`;
  const probe = /^接口返回 HTTP (\d+)，请检查地址、凭据和模型权限$/.exec(message);
  if (probe) return `API returned HTTP ${probe[1]}. Check the URL, credentials and model access.`;
  // RPC failures may include host context around a known validation message.
  for (const [source, target] of Object.entries(english)) if (source.length >= 12 && message.includes(source)) return message.replace(source, target);
  return message;
}
